# Stack for backtracking
Stack = []

# Initiate start and end variables
start = (2, 0)
end = (11, 13)
previous_direction = 1

# Initiate current as start
current = start

# Store traversable paths for each cell
paths = {}

# Helper functions
def get_directions(cell, prev_dir):
    directions = []
    
    # Figure out the backwards direction
    back = -1
    if prev_dir == 0:
        back = 2
    elif prev_dir == 1:
        back = 3
    elif prev_dir == 2:
        back = 0
    elif prev_dir == 3:
        back = 1

    # Check for available directions
    for index, wall in enumerate(Matrix[cell]):
        if index == back:
            continue
        elif wall == 1:
            directions.append(index)

    return directions

def next_cell(curr, direction):
    row, column = curr
    if direction == 0:
        row -= 1
    elif direction == 1:
        column += 1
    elif direction == 2:
        row += 1
    elif direction == 3:
        column -= 1
    return (row, column)

def print_direction(direction):
    if direction == 0:
        dir_name = "North"
    elif direction == 1:
        dir_name = "East"
    elif direction == 2:
        dir_name = "South"
    else:
        dir_name = "West"
    
    # end=" " ensures the next print happens on the same line
    print(dir_name, end=" ")

# Start traversing
print(f"Start at ({current[0]},{current[1]})")

# Keep traversing while current is not end
while current != end:

    # If cell is not in the Stack, add it
    if current not in Stack:
        directions = get_directions(current, previous_direction)
        Stack.append(current)
        paths[current] = directions

    # Check if no directions to move in current cell
    if len(paths[current]) == 0:
        # Prints on the same line as the directions, finishing the line
        print(f"Stuck at ({current[0]},{current[1]})")
        Stack.pop()
        
        # Backtrack to the last cell
        current = Stack[-1]
        print(f"Back to ({current[0]},{current[1]})")
        continue
        
    # Get next moving direction
    next_direction = paths[current].pop(0)

    # Move to next cell
    current = next_cell(current, next_direction)
    print_direction(next_direction)
    previous_direction = next_direction
else:
    # Prints on the same line as the final directions
  print(f"Leaving at ({current[0]},{current[1]})") 
