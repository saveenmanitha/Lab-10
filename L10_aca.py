# Use list as a stack by appending and popping from the end
Stack = []

# Initiate start and end variables
start = (2, 0)
end = (11, 13)
previous_direction = 1

# Initiate current as start
current = start

# Store traversable paths for each cell
paths = {}

# Helper functions
def get_directions(cell, previous_direction):
    
    directions = []

    # Figure out the backwards direction
    if previous_direction == 0:
        back = 2
    elif previous_direction == 1:
        back = 3
    elif previous_direction == 2:
        back = 0
    elif previous_direction == 3:
        back = 1

    # Check for avilable directions
    for index, wall in enumerate(Matrix[cell]):
        # Do not include the backwards direction
        if index == back:
            continue
        elif wall == 1:
            directions.append(index)

    return directions

def next_cell(current, direction):
    row, column = current
    match direction:
        case 0:
            row -= 1
        case 1:
            column += 1
        case 2:
            row += 1
        case 3:
            column -= 1
    next = (row, column)
    return next

def print_direction(direction):
    if direction == 0:
        dir = "North"
    elif direction == 1:
        dir = "East"
    elif direction == 2:
        dir = "South"
    else:
        dir = "West"
    print(dir, end=" ")

# Start traversing
print("Start at ( %i , %i )" % (current[0], current[1]))

# Keep traversing while current is not end
while current != end:

    # If cell is not in the Stack add it
    if current not in Stack:
        # Get traversable directions for current cell
        directions = get_directions(current, previous_direction)
        # Add current cell to stack
        Stack.append(current)
        # Also add the cell and it's movable directions to paths dictionary
        paths[current] = directions

    # Check if no directions to move in current cell
    if len(paths[current]) == 0:
        # Remove that cell from stack
        print("Stuck at ( %i , %i )" % (current[0], current[1]))
        Stack.pop()
        # Back track to last cell
        current = Stack[-1]
        print("Back to ( %i , %i )" % (current[0], current[1]))
        continue
        
    # Get next moving direction
    next_direction = paths[current].pop(0)

    # Move to next cell
    current = next_cell(current, next_direction)
    print_direction(next_direction)
    previous_direction = next_direction
else:
    print("Reached", current)


